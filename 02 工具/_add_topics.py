def chapter(no):
    t = TOPICS[no]
    L = ["", "七、话题与标签", SEP, "【抖音 / 视频号】", "  " + " ".join(t["dy"]),
         "", "【小红书】", "  " + " ".join(t["xhs"]),
         "", "【B站】", "  " + t["bili"], "", ""]
    return "\n".join(L)


def main():
    for no, proj, short, date, arch in EPS:
        deliver = os.path.join(WORK, "30 制作", proj, "30_交付")
        os.makedirs(deliver, exist_ok=True)
        name = "标题与描述_%s_%s.txt" % (no, short if no != "NO.17" else "一百个人等一句话")
        p = os.path.join(deliver, name)
        # NO.17 没有源文件，从归档拷一份
        if not os.path.exists(p):
            src = os.path.join(WORK, "40 出版物", date, arch, name)
            if os.path.exists(src):
                shutil.copy(src, p)
                print("  %s 从归档取回" % no)
            else:
                print("  %s 缺文件，跳过" % no)
                continue
        txt = open(p, encoding="utf-8").read()
        if "七、话题与标签" in txt:
            # 已存在则替换整章
            head = txt.split("七、话题与标签")[0].rstrip() + "\n"
            rewrite_file(p, lambda s, h=head: h + chapter(no))
            print("  %s 替换第七章" % no)
        else:
            rewrite_file(p, lambda s: s.rstrip() + "\n" + chapter(no))
            print("  %s 追加第七章" % no)
        # 同步归档
        dst = os.path.join(WORK, "40 出版物", date, arch, name)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy(p, dst)
        print("     归档同步 -> %s" % os.path.relpath(dst, WORK))


if __name__ == "__main__":
    main()
