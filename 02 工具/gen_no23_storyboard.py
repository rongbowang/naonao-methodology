    chunks.append(d["转场"]); chunks.append(d["连续性"])
    for r in d["音效"]:
        chunks.extend(r)
    for r in d["字卡"]:
        chunks.extend(r)
    for r in d["出入画"]:
        chunks.extend(r)
    chunks.append(d["prompt"])
    seen, out = set(), []
    for c in chunks:
        for h in HEXRE.findall(c):
            u = h.upper()
            if u not in seen:
                seen.add(u); out.append(u)
    return out


